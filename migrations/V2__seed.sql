-- ===========================================================================
-- Derived columns
--
-- The only MIN() over variants anyone should ever write: once, at seed time.
-- At runtime this column is maintained on write, because sort=price_asc reads
-- it on every catalogue request and a subquery there cannot use an index.
-- ===========================================================================

UPDATE products p
SET min_price_cents = COALESCE((
        SELECT MIN(v.price_cents)
        FROM product_variants v
        WHERE v.product_id = p.id AND v.is_active
    ), 0);

-- ===========================================================================
-- Self-check
--
-- A seed that half-applied is worse than one that failed, because the shop
-- still looks fine while the demo cases have quietly gone. These assertions run
-- inside the same migration, so a botched edit fails `make up-node` loudly
-- instead of surfacing three phases later as a flaky concurrency test.
-- ===========================================================================

DO $$
DECLARE
    v_count integer;
BEGIN
    SELECT count(*) INTO v_count FROM users;
    IF v_count <> 3 THEN
        RAISE EXCEPTION 'expected 3 users, found %', v_count;
    END IF;

    SELECT count(*) INTO v_count FROM categories;
    IF v_count <> 8 THEN
        RAISE EXCEPTION 'expected 8 categories, found %', v_count;
    END IF;

    SELECT count(*) INTO v_count FROM products;
    IF v_count <> 15 THEN
        RAISE EXCEPTION 'expected 15 products, found %', v_count;
    END IF;

    SELECT count(*) INTO v_count FROM product_variants;
    IF v_count <> 44 THEN
        RAISE EXCEPTION 'expected 44 variants, found %', v_count;
    END IF;

    -- The concurrency demo needs exactly one unit, not two and not none.
    SELECT stock_on_hand INTO v_count
    FROM product_variants WHERE sku = 'TOTE-M';
    IF v_count <> 1 THEN
        RAISE EXCEPTION 'TOTE-M must hold exactly 1 unit for the concurrency demo, found %', v_count;
    END IF;

    -- The sold-out product must actually be sold out.
    SELECT sum(v.stock_on_hand) INTO v_count
    FROM product_variants v
    JOIN products p ON p.id = v.product_id
    WHERE p.slug = 'kitchen-knife-set';
    IF v_count <> 0 THEN
        RAISE EXCEPTION 'kitchen-knife-set must be fully out of stock, found % units', v_count;
    END IF;

    -- price_asc needs products whose variants disagree on price.
    SELECT count(*) INTO v_count FROM (
        SELECT product_id FROM product_variants
        GROUP BY product_id HAVING count(DISTINCT price_cents) > 1
    ) multi;
    IF v_count < 3 THEN
        RAISE EXCEPTION 'expected at least 3 multi-price products for price_asc, found %', v_count;
    END IF;

    -- The catalogue must have something to hide.
    SELECT count(*) INTO v_count FROM products WHERE status <> 'active';
    IF v_count < 2 THEN
        RAISE EXCEPTION 'expected a draft and an archived product, found % non-active', v_count;
    END IF;

    -- The denormalised column has to agree with the variants it summarises.
    SELECT count(*) INTO v_count
    FROM products p
    WHERE p.min_price_cents <> COALESCE((
        SELECT MIN(v.price_cents) FROM product_variants v
        WHERE v.product_id = p.id AND v.is_active
    ), 0);
    IF v_count <> 0 THEN
