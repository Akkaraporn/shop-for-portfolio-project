-- The point of this file is that `make up-node` on a clean machine opens onto a
-- shop someone would believe. No "Product 1". Real Thai product names, prices
-- that make sense in satang, a category tree with actual depth.
--
-- Three cases are planted deliberately, because each one is a demo or a test
-- that cannot be performed without it:
--
--   * TOTE-M has stock_on_hand = 1 — the concurrency demo. Fire 20 concurrent
--     checkouts at it; exactly one may win.
--   * kitchen-knife-set has every variant at 0 — the sold-out UI state, which
--     is otherwise the kind of thing nobody notices is unstyled until a demo.
--   * cast-iron-pot, cotton-sheet-set-400tc and canvas-tote-bag each have
--     variants at different prices, so sort=price_asc has something to sort and
--     min_price_cents has something to be wrong about.
